# Рассчет стоимости с прогрессивной системой скидок
# Исходные данные
price=float(input("Цена товара = "))
count=float(input("Количество товара = "))
cost=price*count
# Расчет итоговой стоимости
if cost<1000:
  print(f"Ваша скидка - 0%, цена товаров = {cost}")
elif 1000<=cost<=5000:
  print(f"Ваша скидка - 5%, цена товаров без скидки = {cost}, цена со скидкой {cost*0.95}")
elif cost>5000:
  print(f"Ваша скидка - 10%, цена товаров без скидки = {cost}, цена со скидкой {cost*0.9}")
